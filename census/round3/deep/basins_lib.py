"""Exact cycle lists and congruence invariants for certifiable SPLIT members.

Sigma_d (d odd): odd n -> whichever of n+d, 3n+d is divisible by 4; even n -> n/2.
   d = 1 mod 4: Sigma_d = SPLIT(3,1,d);  d = 3 mod 4: Sigma_d = SPLIT(1,3,d).
X_d = SPLIT(1,1,d): odd n -> n+d.
"""
from math import gcd


def sigma_step(d):
    def step(n):
        if n % 2 == 0:
            return n // 2
        return n + d if (n + d) % 4 == 0 else 3 * n + d
    return step


def x_step(d):
    return lambda n: n // 2 if n % 2 == 0 else n + d


def cycle_of(step, n, cap=10 ** 7):
    seen = {}
    k = 0
    while n not in seen:
        seen[n] = k
        n = step(n)
        k += 1
        assert k < cap
    c = [n]
    m = step(n)
    while m != n:
        c.append(m)
        m = step(m)
    return c


def all_cycles(step, d):
    """All cycles: valid when every cycle meets [1, d] (Lemma in basins.md)."""
    cyc = {}
    for n in range(1, d + 1):
        c = cycle_of(step, n)
        cyc[min(c)] = c
    return cyc


def orbit_classes(d, mults):
    """Classes of Z/d under the group generated by multiplication by mults (units mod d)."""
    lab = [-1] * d
    k = 0
    for r in range(d):
        if lab[r] >= 0:
            continue
        st = [r]
        lab[r] = k
        while st:
            x = st.pop()
            for g in mults:
                y = x * g % d
                if lab[y] < 0:
                    lab[y] = k
                    st.append(y)
        k += 1
    return lab, k


def sigma_table(d):
    """For gcd(d,6)=1: cycles, invariant classes (H=<2,3>), and the cycles in each class."""
    assert gcd(d, 6) == 1
    cyc = all_cycles(sigma_step(d), d)
    lab, k = orbit_classes(d, [2, 3])
    per = {}
    for m, c in cyc.items():
        cls = {lab[x % d] for x in c}
        assert len(cls) == 1  # invariance check on the cycle itself
        per.setdefault(cls.pop(), []).append(m)
    return cyc, lab, k, per


