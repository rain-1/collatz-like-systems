# 1. Theorem A at EVERY modulus M <= 240 (odd moduli included, no refinement assumed).
#    Residue graph built empirically: images of r + M t for t = 1..6 (enough: the parity /
#    3-adic branch of r + M t has period <= 3 in t, and the image mod M is then periodic).
#    Claim: from every class the class of the target is reachable.
def reach_all(step, M, target):
    succ = [set(step(r + M * t) % M for t in range(1, 7)) for r in range(M)]
    pred = [[] for _ in range(M)]
    for r in range(M):
        for s in succ[r]:
            pred[s].append(r)
    seen = {target % M}
    st = [target % M]
    while st:
        x = st.pop()
        for y in pred[x]:
            if y not in seen:
                seen.add(y); st.append(y)
    return len(seen) == M

