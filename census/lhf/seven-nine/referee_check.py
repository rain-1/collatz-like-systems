# 2. Theorem C, independent implementation. B_k by exact binary search.
def Bk(q, r, base, k):
    K0 = 0
    P = 1
    qk = q ** k
    while P <= qk:
        P *= base; K0 += 1
    good = lambda n: (q * n + r) ** k >= P * n ** k
    if not good(1):
        return 0
    lo, hi = 1, 2
    while good(hi):
        lo, hi = hi, hi * 2
    while hi - lo > 1:
        mid = (lo + hi) // 2
        if good(mid): lo = mid
        else: hi = mid
    return lo


# speed: precompute kmax via suffix max
def cycles_fast(step, expanding, q, r, base, L):
    B = [0] + [Bk(q, r, base, k) for k in range(1, L + 1)]
    X = max(B)
    kmax = [0] * (X + 2)
    for k in range(1, L + 1):
        kmax[B[k]] = max(kmax[B[k]], k)
    for n in range(X, 0, -1):
        kmax[n] = max(kmax[n], kmax[n + 1])
    found = []
    for n in range(1, X + 1):
        if not expanding(n):
            continue
        x, cnt = n, 0
        while True:
            if expanding(x):
                if x < n:
                    break
                cnt += 1
                if cnt > kmax[n]:
                    break
            x = step(x)
            if x == n:
                found.append(n); break
    return found, X

