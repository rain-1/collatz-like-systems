# 1b. The Lemma (Step 3) directly: on Z/m the semigroup generated by the induced maps
#     moves every s to 1.  Done as reverse BFS from 1 over all words.
def lemma(m, gens):
    pred = [[] for _ in range(m)]
    for x in range(m):
        for f in gens:
            pred[f(x)].append(x)
    seen = {1 % m}; st = [1 % m]
    while st:
        x = st.pop()
        for y in pred[x]:
            if y not in seen:
                seen.add(y); st.append(y)
    return len(seen) == m

