"""Construct lifts of a prefix of 129 with many failures of the same potential.

Fix T, the number of prescribed branches, and B=1024, the padding in P.
Let x=G**T(129). A start 129+3**T*q follows precisely those branches and
ends at x+A*q, where A=2**e and e counts bits appended in the T steps.

Choose arbitrarily large K satisfying

    3**K = 1 + 4**B*(x-1)/3**B       modulo 4**B*A.

Division here is by an odd unit. The target is 1 modulo 8. Every such
residue is a power of 9 modulo a power of 2, since 9**(2**j)-1 is exactly
divisible by 2**(3+j) (induct by squaring). Thus K exists and can be
increased by a full period. Put y=1+3**B*((3**K-1)//4**B). Then y=x mod A
and n=129+3**T*((y-x)//A) is a positive integer for large K. Its first T
branches agree with 129. Its next B inputs are 1 mod 3 since the branch
acts as 1+3*v -> 1+4*v. This brings it exactly to 3**K. The next K inputs
are all multiples of 3.

Write r_i=i+digits_3(G**i(n))+B for the absolute end of the i-th window.
These ends are nondecreasing. Since y < 3**K, r_T <= T+B+K. Also
y > 3**(K-B), and G(z) <= 2*z gives n >= y/2**T. Hence r_0 > K-T.
For K > 4*(T+B), every r_i, 0 <= i <= T, is beyond 3*(T+B) and
inside the stretch of +5 deficits (including its right endpoint).
The first T+B steps have absolute running deficit at most 5*(T+B)
and end at deficit at least -3*(T+B). After another 2*(T+B) steps
the deficit exceeds every earlier value and it keeps rising to r_T.
Each window maximum is therefore its rightmost deficit. Whenever
the i-th input is a nonmultiple of 3, G increases the lifted input
(which is >1), r_{i+1} >= r_i+1, and the maximum increases by at least 5.
That is a genuine positive defect at the i-th step.

Finally, for T >= 64 the true orbit of 129 has fewer than T/2 multiples
of 3 in its first T inputs: all values are >=8, while T/2 or more such
inputs would give G**T(129) <= 129*(11/12)**(T/2) < 8. Here 11/8 is
the largest possible nonmultiple growth factor for inputs >=8. Thus
strictly more than half of the lifted steps fail. The statement is
about different integer starts for each T, not later visits from 129.
"""

import argparse

from verify_binary_invariant import orbit_step
from verify_cofactor_potential import PADDING


def construct_exponent(endpoint, bits, steps, padding):
    width = 2*padding + bits
    modulus = 1 << width
    target = (1 + (1 << (2*padding)) * (endpoint-1)
              * pow(3, -padding, modulus)) % modulus
    if target % 8 != 1:
        raise AssertionError("Target must be in the subgroup generated by nine")
    residue, power, exponent = 1, 9, 0
    for bit in range(3, width):
        if ((target ^ residue) >> bit) & 1:
            exponent += 1 << (bit-3)
            residue = residue*power % modulus
        power = power*power % modulus
    k = 2*exponent
    period = 1 << (width-2)
    while k <= 4*(steps+padding):
        k += period
    if pow(3, k, modulus) != target:
        raise AssertionError("Incorrect exponent in the lift")
    return k


def verify(steps):
    x, bits, units = 129, 0, 0
    for _ in range(steps):
        nonzero = x % 3 != 0
        units += nonzero
        bits += 1 + nonzero
        x = orbit_step(x)
    if 129 * 11**32 >= 8 * 12**32 or 2*units <= steps:
        raise AssertionError("Nonmultiple count did not clear half the interval")
    k = construct_exponent(x, bits, steps, PADDING)
    print(f"Matched {steps} residue branches; at least {units} lifted steps fail.")
    print(f"Verified the power congruence exactly; the exponent K has {k.bit_length()} binary digits.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--steps", type=int, default=64)
    args = parser.parse_args()
    if args.steps < 64:
        parser.error("Use at least 64 steps for the half-interval bound")
    verify(args.steps)
